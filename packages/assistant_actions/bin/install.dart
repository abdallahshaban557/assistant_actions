// Sets an app up for assistant_actions. Run once from the app's root:
//
//   dart run assistant_actions:install
//
// It is safe to run again; each step skips what is already done.

import 'dart:io';
import 'dart:math';

const _plugin = 'assistant_actions_app';
const _shortcuts = 'AssistantShortcuts.g.swift';

void main(List<String> args) {
  final root = Directory.current;
  final pubspec = File('${root.path}/pubspec.yaml');
  if (!pubspec.existsSync() || !pubspec.readAsStringSync().contains(RegExp(r'^\s+assistant_actions:', multiLine: true))) {
    stderr.writeln('Run this from the root of an app that depends on assistant_actions.');
    exit(64);
  }

  _scaffoldPlugin(root);
  _addDependency(pubspec);
  _write(File('${root.path}/apple/$_shortcuts'), '// Generated by assistant_actions_generator: run build_runner.\n',
      overwrite: false);
  for (final platform in ['ios', 'macos']) {
    final project = File('${root.path}/$platform/Runner.xcodeproj/project.pbxproj');
    if (!project.existsSync()) continue;
    var pbx = project.readAsStringSync();
    pbx = _addToRunner(pbx, '../apple/$_shortcuts', _shortcuts, platform);
    pbx = _raiseDeploymentTarget(pbx, platform);
    project.writeAsStringSync(pbx);
  }

  stdout.writeln('''

Next:
  flutter pub get
  dart run build_runner build

Whenever the generated actions or entities change, bump the build number
(the +N in pubspec.yaml's version) before running the app: Siri caches App
Intents per build number.
''');
}

void _scaffoldPlugin(Directory root) {
  final dir = '${root.path}/packages/$_plugin';
  _write(File('$dir/pubspec.yaml'), '''
# Generated by `dart run assistant_actions:install`. The Swift in darwin/ is
# written by assistant_actions_generator; this package only carries it into
# the iOS and macOS builds.
name: $_plugin
description: App Intents generated by assistant_actions for this app.
publish_to: none
version: 0.0.0

environment:
  sdk: ^3.6.0
  flutter: '>=3.27.0'

dependencies:
  flutter:
    sdk: flutter

flutter:
  plugin:
    platforms:
      ios:
        pluginClass: AssistantActionsAppPlugin
        sharedDarwinSource: true
      macos:
        pluginClass: AssistantActionsAppPlugin
        sharedDarwinSource: true
''');
  _write(File('$dir/lib/$_plugin.dart'), '/// Native-only: see darwin/.\nlibrary;\n');
  _write(File('$dir/darwin/$_plugin/Package.swift'), '''
// swift-tools-version: 5.9
// Generated by `dart run assistant_actions:install`.
import PackageDescription

let package = Package(
  name: "$_plugin",
  platforms: [.iOS("17.0"), .macOS("14.0")],
  products: [.library(name: "${_plugin.replaceAll('_', '-')}", targets: ["$_plugin"])],
  dependencies: [
    .package(name: "FlutterFramework", path: "../FlutterFramework"),
    // Flutter puts every plugin side by side, so the runtime is a sibling.
    .package(name: "assistant_actions", path: "../assistant_actions"),
  ],
  targets: [
    .target(
      name: "$_plugin",
      dependencies: [
        .product(name: "FlutterFramework", package: "FlutterFramework"),
        .product(name: "assistant-actions", package: "assistant_actions"),
      ])
  ]
)
''');
  final sources = '$dir/darwin/$_plugin/Sources/$_plugin';
  _write(File('$sources/AssistantActionsAppPlugin.swift'), '''
// Generated by `dart run assistant_actions:install`.
#if os(iOS)
  import Flutter
#else
  import FlutterMacOS
#endif

/// Flutter needs a plugin class; the App Intents in AssistantActions.g.swift
/// need no registration.
public final class AssistantActionsAppPlugin: NSObject, FlutterPlugin {
  public static func register(with registrar: FlutterPluginRegistrar) {}
}
''');
  _write(File('$sources/AssistantActions.g.swift'), '// Generated by assistant_actions_generator: run build_runner.\n',
      overwrite: false);
}

void _addDependency(File pubspec) {
  final text = pubspec.readAsStringSync();
  if (text.contains(RegExp('^\\s+$_plugin:', multiLine: true))) {
    _report('pubspec.yaml already depends on $_plugin');
    return;
  }
  final updated = text.replaceFirst(
    RegExp(r'^dependencies:[ \t]*\n', multiLine: true),
    'dependencies:\n  $_plugin:\n    path: packages/$_plugin\n',
  );
  if (updated == text) {
    stderr.writeln('Could not find `dependencies:` in pubspec.yaml; add $_plugin (path: packages/$_plugin) yourself.');
    return;
  }
  pubspec.writeAsStringSync(updated);
  _report('Added $_plugin to pubspec.yaml');
}

/// Adds [path] (relative to the project folder) to the Runner group and the
/// Runner target's Sources build phase.
String _addToRunner(String pbx, String path, String name, String platform) {
  if (pbx.contains('/* $name */')) {
    _report('$platform: $name is already in the Runner target');
    return pbx;
  }
  final fileRef = _id(), buildFile = _id();
  final target = RegExp(r'\w{24} /\* Runner \*/ = \{\s*isa = PBXNativeTarget;[\s\S]*?buildPhases = \(([\s\S]*?)\);')
      .firstMatch(pbx);
  final sources = target == null ? null : RegExp(r'(\w{24}) /\* Sources \*/').firstMatch(target.group(1)!)?.group(1);
  final group = RegExp(r'\w{24} /\* Runner \*/ = \{\s*isa = PBXGroup;\s*children = \(\n').firstMatch(pbx);
  final phase = sources == null
      ? null
      : RegExp('$sources /\\* Sources \\*/ = \\{\\s*isa = PBXSourcesBuildPhase;[^(]*files = \\(\\n').firstMatch(pbx);
  if (group == null || phase == null) {
    stderr.writeln('$platform: could not find the Runner group or target. Add apple/$name to Runner in Xcode.');
    return pbx;
  }
  // Insert from the end of the file backwards so earlier offsets stay valid.
  final edits = [
    (phase.end, '\t\t\t\t$buildFile /* $name in Sources */,\n'),
    (group.end, '\t\t\t\t$fileRef /* $name */,\n'),
  ]..sort((a, b) => b.$1.compareTo(a.$1));
  for (final (at, text) in edits) {
    pbx = pbx.replaceRange(at, at, text);
  }
  pbx = pbx
      .replaceFirst('/* Begin PBXBuildFile section */\n',
          '/* Begin PBXBuildFile section */\n\t\t$buildFile /* $name in Sources */ = {isa = PBXBuildFile; fileRef = $fileRef /* $name */; };\n')
      .replaceFirst('/* Begin PBXFileReference section */\n',
          '/* Begin PBXFileReference section */\n\t\t$fileRef /* $name */ = {isa = PBXFileReference; lastKnownFileType = sourcecode.swift; name = $name; path = $path; sourceTree = SOURCE_ROOT; };\n');
  _report('$platform: added apple/$name to the Runner target');
  return pbx;
}

/// App Intents packages here need iOS 17 / macOS 14.
String _raiseDeploymentTarget(String pbx, String platform) {
  final (key, minimum) = platform == 'ios' ? ('IPHONEOS_DEPLOYMENT_TARGET', 17.0) : ('MACOSX_DEPLOYMENT_TARGET', 14.0);
  var raised = false;
  final updated = pbx.replaceAllMapped(RegExp('$key = ([0-9.]+);'), (m) {
    if ((double.tryParse(m[1]!) ?? 0) >= minimum) return m[0]!;
    raised = true;
    return '$key = ${minimum.toStringAsFixed(1)};';
  });
  if (raised) _report('$platform: raised $key to ${minimum.toStringAsFixed(1)}');
  return updated;
}

void _write(File file, String content, {bool overwrite = true}) {
  if (file.existsSync() && (!overwrite || file.readAsStringSync() == content)) return;
  file.parent.createSync(recursive: true);
  file.writeAsStringSync(content);
  _report('Wrote ${file.path.replaceFirst('${Directory.current.path}/', '')}');
}

final _random = Random.secure();
String _id() => List.generate(24, (_) => '0123456789ABCDEF'[_random.nextInt(16)]).join();

void _report(String message) => stdout.writeln('  $message');
