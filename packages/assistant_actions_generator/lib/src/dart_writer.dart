import 'catalog.dart';
import 'model.dart';
import 'schema_calls.dart';
import 'schema_library.dart' show schemaLibraryFile;

/// Writes `lib/assistant_actions.g.dart`: the registry `AssistantActions.start`
/// takes, plus a typed handler interface per schema entity.
String writeDart(AppModel app) {
  final prefixes = <Uri, String>{};
  var i = 0;
  for (final uri in app.libraries) {
    prefixes[uri] = 'a${i++}';
  }
  String ref(Uri library, String name) => '${prefixes[library]}.$name';

  final out = StringBuffer()
    ..writeln('// GENERATED by assistant_actions_generator. Do not edit.')
    ..writeln('// ignore_for_file: type=lint')
    ..writeln()
    ..writeln("import 'dart:async';");
  // jsonEncode, for handlers that return several ids.
  final returnsLists = [
    for (final s in app.schemaEntities)
      for (final (i, k) in s.intents)
        if (k == IntentKind.call) i,
    for (final d in app.schemaDomains) ...d.intents,
  ].any((i) => const {CallResult.entities, CallResult.union, CallResult.unions}.contains(callResult(i)));
  if (returnsLists) out.writeln("import 'dart:convert';");
  out
    ..writeln()
    ..writeln("import 'package:assistant_actions/assistant_actions.dart';");
  // Schema enums the handlers and values use, by domain.
  final enums = <String, Set<String>>{};
  void useEnum(String ref) => (enums[ref.split('.').first] ??= {}).add(dartEnumName(ref));
  for (final s in app.schemaEntities) {
    for (final f in s.fields) {
      if (f.type.enumRef case final r? when f.type.appEnum == null) useEnum(r);
    }
  }
  final appEnums = <Uri, Set<String>>{};
  void useAppEnum(String ref) {
    final e = app.openEnums[ref]!;
    (appEnums[e.library] ??= {}).add(e.className);
  }

  for (final s in app.schemaEntities) {
    for (final f in s.fields) {
      if (f.type.appEnum != null) useAppEnum(f.type.enumRef!);
    }
  }
  for (final intent in [
    for (final s in app.schemaEntities)
      for (final (i, k) in s.intents)
        if (k == IntentKind.call) i,
    for (final d in app.schemaDomains) ...d.intents,
  ]) {
    for (final p in intent.parameters) {
      if (callArg(p) case final a? when a.element.kind == 'enum') useEnum(a.element.ref!);
      if (callArg(p) case final a? when a.element.kind == 'openEnum') useAppEnum(a.element.ref!);
    }
  }
  for (final MapEntry(key: domain, value: names) in (enums.entries.toList()..sort((a, b) => a.key.compareTo(b.key)))) {
    out.writeln("import 'package:assistant_actions/schemas/${schemaLibraryFile(domain)}' show ${(names.toList()..sort()).join(', ')};");
  }
  out.writeln();
  for (final MapEntry(:key, :value) in prefixes.entries) {
    out.writeln("import '$key' as $value;");
  }
  // The app's enums for schema enums whose cases it defines, by name.
  for (final MapEntry(:key, :value) in appEnums.entries) {
    out.writeln("import '$key' show ${(value.toList()..sort()).join(', ')};");
  }

  // ── Handler interfaces for schema entities ──
  for (final s in app.schemaEntities) {
    final values = '${s.className}Values';
    out
      ..writeln()
      ..writeln('/// Siri\'s values for a `${s.className}` (`${s.schema.id}`).')
      ..writeln('///')
      ..writeln('/// A null field is unchanged, unless its `…Cleared` getter says Siri removed')
      ..writeln('/// the value.')
      ..writeln('class $values {')
      ..writeln('  const $values({${[for (final f in s.fields) 'this.${f.name}', 'this.cleared = const {}'].join(', ')}});')
      ..writeln();
    for (final f in s.fields) {
      out.writeln('  final ${f.type.dart.replaceAll('?', '')}? ${f.name};');
    }
    out
      ..writeln()
      ..writeln('  /// Fields Siri cleared (set to no value), by Dart field name.')
      ..writeln('  final Set<String> cleared;');
    for (final f in s.fields.where((f) => f.type.nullable)) {
      out
        ..writeln()
        ..writeln('  /// Siri removed `${f.name}` (for example, took a due date off a reminder).')
        ..writeln("  bool get ${f.name}Cleared => cleared.contains('${f.name}');");
    }
    final takesValues = s.kinds.any((k) => k == IntentKind.create || k == IntentKind.update || k == IntentKind.append);
    if (takesValues) {
      out
        ..writeln()
        ..writeln('  static $values _from(Map<String, Object?> f, List<String> cleared) => $values(');
      for (final f in s.fields) {
        out.writeln("        ${f.name}: ${f.type.decodeDart("f['${f.name}']")},");
      }
      out
        ..writeln('        cleared: {...cleared},')
        ..writeln('      );');
    }
    out
      ..writeln('}')
      ..writeln()
      ..writeln('/// Applies the changes Siri makes to `${s.className}` items through')
      ..writeln('/// ${s.intents.map((e) => '`${e.$1.id}`').join(', ')}.')
      ..writeln('abstract interface class ${s.className}AssistantHandler {');
    for (final kind in s.kinds) {
      switch (kind) {
        case IntentKind.create:
          out
            ..writeln('  /// Siri created an item. Keep [id]: later updates and deletes use it.')
            ..writeln('  Future<void> create(String id, $values values);');
        case IntentKind.update || IntentKind.append:
          out.writeln('  Future<void> update(String id, $values changes);');
        case IntentKind.delete:
          out.writeln('  Future<void> delete(String id);');
        case IntentKind.record:
          for (final (intent, k) in s.intents) {
            if (k != IntentKind.record) continue;
            out
              ..writeln()
              ..writeln('  /// Siri asked for `${intent.id}` ("${intent.title}"). The app is in the')
              ..writeln('  /// foreground: start recording, and save the item when the user stops.')
              ..writeln('  Future<void> ${recordMethod(intent)}();');
          }
        case IntentKind.call:
          for (final (intent, k) in s.intents) {
            if (k == IntentKind.call) _callMethod(out, intent, s.schema, app.openEnumNames);
          }
      }
    }
    out.writeln('}');
  }

  // ── Handler interfaces for schema domains ──
  for (final d in app.schemaDomains) {
    out
      ..writeln()
      ..writeln("/// Handles Apple's `${d.domain}` intents turned on with `@${pascal(d.domain)}Intents` on `${d.className}`.")
      ..writeln('abstract interface class ${d.handler} {');
    for (final intent in d.intents) {
      if (intent.id == 'system.open') {
        for (final name in [
          for (final s in app.schemaEntities)
            if (!s.hasOwnOpen) s.className,
          for (final e in app.entities) e.className,
        ]) {
          out
            ..writeln()
            ..writeln('  /// Siri asked to open the `$name` with [id] (`system.open`): show it.')
            ..writeln('  Future<void> open$name(String id);');
        }
        continue;
      }
      _callMethod(out, intent, null, app.openEnumNames);
    }
    out.writeln('}');
  }

  // ── Registry ──
  final finders = {
    for (final a in app.actions)
      for (final p in a.params)
        if (p.entity != null) p.entity!.className: p.entity!,
  }.values;
  final args = [
    for (final e in finders) 'required FutureOr<${ref(e.library, e.className)}?> Function(String id) find${e.className},',
    for (final s in app.schemaEntities) 'required ${s.className}AssistantHandler ${camel(s.className)},',
    for (final d in app.schemaDomains) 'required ${d.handler} ${d.parameter},',
  ];
  out
    ..writeln()
    ..writeln('/// Pass to `AssistantActions.start`.')
    ..writeln(args.isEmpty
        ? 'AssistantActionsRegistry assistantActionsRegistry() => AssistantActionsRegistry('
        : 'AssistantActionsRegistry assistantActionsRegistry({${args.join(' ')}}) => AssistantActionsRegistry(')
    ..writeln('  actions: {');
  for (final a in app.actions) {
    out.writeln("    '${a.id}': (args) async {");
    final callArgs = <String>[];
    for (final p in a.params) {
      final local = '_${p.name}';
      if (p.entity case final e?) {
        out.writeln("      final $local = args['${p.name}'] is String ? await find${e.className}(args['${p.name}'] as String) : null;");
        if (!p.entityNullable) out.writeln('      if ($local == null) return null;');
      } else {
        final decode = p.value!.decodeDart("args['${p.name}']");
        out.writeln(p.nullable
            ? '      final $local = $decode;'
            : "      final $local = $decode ?? (throw ArgumentError.notNull('${p.name}'));");
      }
      callArgs.add(p.named ? '${p.name}: $local' : local);
    }
    final call = '${ref(a.library, a.functionName)}(${callArgs.join(', ')})';
    out.writeln(a.returnsString ? '      return await $call;' : '      await $call;\n      return null;');
    out.writeln('    },');
  }
  // Record intents (`journal.createAudioEntry`) call the handler live, once
  // Swift has brought the app forward. A `.` keeps the ids apart from
  // function names.
  for (final s in app.schemaEntities) {
    for (final (intent, kind) in s.intents) {
      if (kind != IntentKind.record) continue;
      out
        ..writeln("    '${recordActionId(s, intent)}': (args) async {")
        ..writeln('      await ${camel(s.className)}.${recordMethod(intent)}();')
        ..writeln('      return null;')
        ..writeln('    },');
    }
  }
  // Other schema intents call a handler method with their parameters.
  for (final s in app.schemaEntities) {
    for (final (intent, kind) in s.intents) {
      if (kind == IntentKind.call) {
        _callEntry(out, callActionId(s, intent), camel(s.className), intent, s.schema, app.openEnumNames);
      }
    }
  }
  for (final d in app.schemaDomains) {
    for (final intent in d.intents) {
      if (intent.id == 'system.open') {
        for (final name in [
          for (final s in app.schemaEntities)
            if (!s.hasOwnOpen) s.className,
          for (final e in app.entities) e.className,
        ]) {
          out
            ..writeln("    'system.open.$name': (args) async {")
            ..writeln("      await ${d.parameter}.open$name(AssistantValue.string(args['id']) ?? (throw ArgumentError.notNull('id')));")
            ..writeln('      return null;')
            ..writeln('    },');
        }
        continue;
      }
      _callEntry(out, callActionId(null, intent), d.parameter, intent, null, app.openEnumNames);
    }
  }
  out
    ..writeln('  },')
    ..writeln('  codecs: {');
  for (final e in app.entities) {
    final type = ref(e.library, e.className);
    out
      ..writeln("    $type: EntityCodec<$type>('${e.className}',")
      ..writeln('      id: (e) => e.${e.idField},')
      ..writeln('      title: (e) => e.${e.titleGetter},')
      ..writeln(e.subtitleGetter == null ? '' : '      subtitle: (e) => e.${e.subtitleGetter},')
      ..writeln(e.fields.isEmpty
          ? '      fields: (e) => const {},'
          : "      fields: (e) => {${e.fields.map((f) => "'${f.name}': ${f.type.encodeDart('e.${f.name}')}").join(', ')}},")
      ..writeln('    ),');
  }
  for (final s in app.schemaEntities) {
    final type = ref(s.library, s.className);
    final title = s.schema.titleProperty;
    final titleField = title == null ? null : s.mapping[title.name];
    out
      ..writeln("    $type: EntityCodec<$type>('${s.collection}',")
      ..writeln('      id: (e) => e.${s.idField},')
      ..writeln(titleField == null
          ? "      title: (e) => '${s.schema.title}',"
          : "      title: (e) => e.${titleField.name}${titleField.type.nullable ? " ?? ''" : ''},")
      ..writeln('      fields: (e) => {');
    for (final f in s.fields) {
      out.writeln("        '${f.name}': ${f.type.encodeDart('e.${f.name}')},");
    }
    out
      ..writeln('      },')
      ..writeln('    ),');
  }
  out
    ..writeln('  },')
    ..writeln('  collections: {');
  for (final s in app.schemaEntities) {
    final handler = camel(s.className);
    // Only create, update and delete arrive as changes.
    if (!s.kinds.any((k) => k != IntentKind.record && k != IntentKind.call)) continue;
    final takesValues = s.kinds.any((k) => k == IntentKind.create || k == IntentKind.update || k == IntentKind.append);
    out.writeln("    '${s.collection}': (change) async {");
    if (takesValues) out.writeln('      final values = ${s.className}Values._from(change.fields, change.cleared);');
    out
      .writeln('      switch (change.kind) {');
    for (final kind in s.kinds) {
      final call = switch (kind) {
        IntentKind.create => '$handler.create(change.id, values)',
        IntentKind.update || IntentKind.append => '$handler.update(change.id, values)',
        IntentKind.delete => '$handler.delete(change.id)',
        // Called as actions, not field changes.
        IntentKind.record || IntentKind.call => null,
      };
      if (call == null) continue;
      out.writeln("        case '${kind.name}':\n          await $call;");
    }
    out
      ..writeln('      }')
      ..writeln('    },');
  }
  out
    ..writeln('  },')
    ..writeln(');');
  return out.toString();
}

/// The handler method declaration for a [IntentKind.call] intent.
void _callMethod(StringBuffer out, IntentSchema intent, EntitySchema? owner, Map<String, String> openEnums) {
  out
    ..writeln()
    ..writeln('  /// Siri\'s `${intent.id}` ("${intent.title}")'
        '${intent.isLive ? '' : ', applied when the app next runs'}.');
  if (intent.description case final d?) out.writeln('  /// $d');
  final dropped = droppedArgs(intent);
  if (dropped.isNotEmpty) {
    out.writeln('  ///\n  /// Not passed yet: ${dropped.map((p) => '`${p.name}` (`${p.type}`)').join(', ')}.');
  }
  for (final p in intent.parameters) {
    if (callArg(p)?.shape == ArgShape.entity) {
      out.writeln('  ///\n  /// `${dartName(p.name)}` is the id of a `${p.type.element.ref}` item.');
      break;
    }
  }
  switch (callResult(intent)) {
    case CallResult.entity || CallResult.entities:
      out.writeln('  ///\n  /// Return the id of the ${resultEntity(intent)} item(s), published first, for Siri to show.');
    case CallResult.union || CallResult.unions:
      out.writeln('  ///\n  /// Return `${intent.result!.element.ref}` case(s). Entity cases are ids of items the app '
          'adopts and has published.');
    default:
  }
  out.writeln('  ${callSignature(intent, owner, openEnums)};');
}

/// Decodes one argument Swift sent for [a].
String _decodeArg(CallArg a) {
  final raw = "args['${a.member.name}']";
  String element(String v) =>
      a.shape == ArgShape.entity ? 'AssistantValue.string($v)' : valueTypeFor(a.element, a.openEnums).decodeDart(v);
  final value = a.list ? 'AssistantValue.list($raw, (v) => ${element('v')})' : element(raw);
  return a.optional ? value : "$value ?? (throw ArgumentError.notNull('${a.name}'))";
}

/// The registry entry that runs a [IntentKind.call] intent's handler method.
void _callEntry(
    StringBuffer out, String id, String handler, IntentSchema intent, EntitySchema? owner, Map<String, String> openEnums) {
  final args = [
    for (final p in intent.parameters)
      if (callArg(p, openEnums) case final a?) '${a.name}: ${_decodeArg(a)}',
  ];
  final call = '$handler.${callMethod(intent, owner)}(${args.join(', ')})';
  out
    ..writeln("    '$id': (args) async {")
    ..writeln(switch (callResult(intent)) {
      CallResult.entity => '      return await $call;',
      CallResult.entities => '      return jsonEncode(await $call);',
      CallResult.union => '      return jsonEncode(AssistantValue.encodeUnion(await $call));',
      CallResult.unions => '      return jsonEncode([for (final u in await $call) AssistantValue.encodeUnion(u)]);',
      _ => '      await $call;\n      return null;',
    })
    ..writeln('    },');
}

/// Writes `apple/AssistantShortcuts.g.swift`, the one file that must be in
/// the app's Runner targets: Apple only reads App Shortcuts from the app.
String writeShortcuts(AppModel app) {
  final shortcuts = [
    for (final a in app.actions)
      if (a.shortcut case final s?) (a.swiftName, s),
    for (final a in app.snapshotActions)
      if (a.shortcut case final s?) (a.swiftName, s),
  ];
  final out = StringBuffer()
    ..writeln('// GENERATED by assistant_actions_generator. Do not edit.')
    ..writeln('// Must be in both Runner targets (dart run assistant_actions:install adds it).')
    ..writeln();
  if (shortcuts.isEmpty) {
    out.writeln('// No @AssistantAction has a shortcut, so there is no AppShortcutsProvider.');
    return out.toString();
  }
  out
    ..writeln('import AppIntents')
    ..writeln('import assistant_actions_app')
    ..writeln()
    ..writeln('struct AssistantShortcuts: AppShortcutsProvider {')
    ..writeln('  static var appShortcuts: [AppShortcut] {');
  for (final (swiftName, s) in shortcuts) {
    final phrases = s.phrases.map((p) => '"${_swiftString(p).replaceAll('{app}', r'\(.applicationName)')}"');
    out
      ..writeln('    AppShortcut(')
      ..writeln('      intent: $swiftName(),')
      ..writeln('      phrases: [${phrases.join(', ')}],')
      ..writeln('      shortTitle: "${_swiftString(s.shortTitle)}",')
      ..writeln('      systemImageName: "${_swiftString(s.systemImage)}")');
  }
  out
    ..writeln('  }')
    ..writeln('}');
  return out.toString();
}

String _swiftString(String s) => s.replaceAll(r'\', r'\\').replaceAll('"', r'\"');
