  void _adoptedEntity(SchemaEntityModel s) {
    final schema = s.schema;
    final name = s.swiftName;
    _out
      ..writeln('/// `${s.className}` in Dart, as `${schema.id}`.')
      ..writeln(_availability(schema.availability))
      ..writeln('@AppEntity(schema: .${schema.id})')
      ..writeln('struct $name {')
      ..writeln('  static let defaultQuery = ${name}Query()')
      ..writeln()
      ..writeln('  let id: String');
    final queryables = _schemaQueryables(s);
    for (final p in schema.properties) {
      // Queryable members need a title for Apple's metadata.
      if (queryables.any((q) => q.member == p.name)) _out.writeln('  @Property(title: "${_escape(p.title)}")');
      _out.writeln('  var ${p.name}: ${_swiftType(p.type)}');
    }
    _out
      ..writeln()
      ..writeln('  var displayRepresentation: DisplayRepresentation {'
          ' DisplayRepresentation(title: "\\(${_titleExpr(schema, '')})") }')
      ..writeln()
      ..writeln('  init(record: AssistantRecord) {')
      ..writeln('    id = record.id');
    for (final p in schema.properties) {
      final field = s.mapping[p.name];
      final value = field != null
          ? _decode(p.type, 'record.fields["${field.name}"]', schema)
          : _default(p.type, schema, s.containers[p.name]);
      _out.writeln('    ${p.name} = $value');
    }
    final collection = s.collection;
    _out.writeln('''
  }
