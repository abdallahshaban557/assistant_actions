/// Writes `AssistantActions.g.swift`, compiled into the generated
/// `assistant_actions_app` plugin.
class SwiftWriter {
  SwiftWriter(this.app);

  final AppModel app;
  final _out = StringBuffer();
  /// Frameworks the schema types need: GeoToolbox for `PlaceDescriptor`, ….
  final _imports = <String>{};

  /// Schema id → the app class adopting it.
  late final Map<String, SchemaEntityModel> _adopted = {for (final s in app.schemaEntities) s.schema.id: s};

  /// Container schema id → its fixed instance, from every annotation.
  final _fixed = <String, FixedInstance>{};

  String write() {
    for (final s in app.schemaEntities) {
      for (final MapEntry(:key, :value) in s.containers.entries) {
        _registerFixed(value, s, key);
      }
    }
    final body = StringBuffer();
    for (final e in app.appEnums.values) {
      _appEnum(e);
    }
    for (final e in app.entities) {
      _entity(e);
    }
    _actionImports();
    for (final a in app.actions) {
      a.focusFilter == null ? _plainAction(a) : _focusFilter(a);
    }
    for (final a in app.snapshotActions) {
      _snapshotAction(a);
    }
    if (app.schemaEntities.isNotEmpty || app.schemaDomains.isNotEmpty || _actionSchemaTypes.isNotEmpty) _schemas();
    _spotlight();
    _imageHelpers();
    _entityConformances();
    _backgroundEntrypoint();
    _intelligence();
    body.write(_publicize(_out.toString()));

    return [
      '// GENERATED by assistant_actions_generator. Do not edit.',
      '// Source: lib/assistant_actions.dart',
      '',
      'import AppIntents',
      'import CoreSpotlight',
      // `Transferable` entities.
      'import CoreTransferable',
      'import Foundation',
      for (final framework in _imports.toList()..sort())
        if (_optionalFrameworks.contains(framework))
          '#if canImport($framework)\n  import $framework\n#endif'
        else
          'import $framework',
      'import assistant_actions',
      '',
      '#if os(iOS)',
      '  import UIKit',
      '#elseif os(macOS)',
      '  import AppKit',
      '#endif',
      '',
      body.toString(),
    ].join('\n');
  }

  void _registerFixed(FixedInstance fixed, SchemaEntityModel owner, String member) {
    final existing = _fixed[fixed.schema];
    if (existing != null && !existing.sameAs(fixed)) {
      throw InvalidGenerationSourceError(
          '${owner.className}.$member gives ${fixed.schema} a different fixed instance than another '
          'annotation. Use the same one everywhere.');
    }
    _fixed[fixed.schema] = fixed;
    for (final MapEntry(:key, :value) in fixed.nested.entries) {
      _registerFixed(value, owner, '$member.$key');
    }
  }

  // ── Plain entities and actions ────────────────────────────────────────

  void _entity(EntityModel e) {
    final name = e.swiftName;
    final fields = _plainQueryables(e);
    _out.writeln('''
/// `${e.className}`, published from Dart with `AssistantActions.publish`.
public struct $name: AppEntity {
  public static let typeDisplayRepresentation: TypeDisplayRepresentation = "${_escape(e.title)}"
  public static let defaultQuery = ${name}Query()

  public let id: String
  @Property(title: "Title")
  public var title: String
  public let subtitle: String?
${_imageDeclaration(e.image, access: 'public ')}${[for (final q in fields) '  @Property(title: "${_escape(q.title)}")\n  public var ${q.member}: ${q.swiftType}\n'].join()}
  public var displayRepresentation: DisplayRepresentation {
${switch (_displayImage(e.systemImage, e.image)) {
      final image? => '    DisplayRepresentation(title: "\\(title)", subtitle: subtitle.map { "\\(\$0)" }, image: $image)',
      null => '    if let subtitle { return DisplayRepresentation(title: "\\(title)", subtitle: "\\(subtitle)") }\n'
          '    return DisplayRepresentation(title: "\\(title)")',
    }}
  }

  init(record: AssistantRecord) {
    id = record.id
    subtitle = record.subtitle
${_imageInit(e.image)}    // `@Property` members last: setting one needs every stored property set.
    title = record.title
${[for (final f in e.fields)
      if (fields.any((q) => q.member == f.name)) '    ${f.name} = AssistantValues.${f.type.swiftDecoder}(record.fields["${f.name}"])\n'].join()}  }
}

public struct ${name}Query: EntityStringQuery, EnumerableEntityQuery, EntityPropertyQuery {
  /// Words that only name the type or app, so they never narrow a search.
  static let typeWords: Set<String> = ${_typeWords([e.className, e.title])}

  public init() {}

  public func entities(for identifiers: [String]) async throws -> [$name] {
    let wanted = Set(identifiers)
    return AssistantSnapshot.records("${e.className}").filter { wanted.contains(\$0.id) }.map($name.init(record:))
  }

  public func entities(matching string: String) async throws -> [$name] {
    AssistantMatch.records(AssistantSnapshot.records("${e.className}"), matching: string, ignoring: Self.typeWords)
      .map($name.init(record:))
  }

  public func suggestedEntities() async throws -> [$name] {
    AssistantSnapshot.records("${e.className}").prefix(20).map($name.init(record:))
  }

  /// Everything published, plus Siri's pending changes, for requests like
  /// "do I have any ${e.title.toLowerCase()}s".
  public func allEntities() async throws -> [$name] {
    AssistantSnapshot.records("${e.className}").map($name.init(record:))
  }

${_propertyQuery(name, [const _Queryable('title', 'Title', 'string', optional: false, isTitle: true), ...fields], 'AssistantSnapshot.records("${e.className}").map($name.init(record:))', 'public ')}}
''');
  }

  /// The fields of a plain entity Siri can filter and sort by, beyond its title.
  List<_Queryable> _plainQueryables(EntityModel e) => [
    for (final f in e.fields)
      if (!const {'id', 'title', 'subtitle', 'displayRepresentation'}.contains(f.name) &&
          f.name != e.titleGetter &&
          !f.name.contains(r'$'))
        if (switch (f.type.kind) {
              ValueKind.string => 'string',
              ValueKind.integer => 'int',
              ValueKind.decimal => 'double',
              ValueKind.boolean => 'bool',
              ValueKind.dateTime => 'date',
              _ => null,
            }
            case final kind?)
          _Queryable(
            f.name,
            _words(f.name),
            kind,
            optional: true,
            swiftType: ValueType(f.type.kind, nullable: true).swift,
          ),
  ];

  /// `dueDate` → `Due Date`.
  static String _words(String name) =>
      pascal(name.replaceAllMapped(RegExp('([a-z0-9])([A-Z])'), (m) => '${m[1]} ${m[2]}'));

  /// Comparators Siri can use on a property of schema kind [kind], as
  /// (App Intents comparator, `AssistantComparison.Operator`).
  static List<(String, String)>? _comparators(String kind) => switch (kind) {
    'bool' => const [('EqualToComparator', 'equal')],
    'date' || 'dateComponents' || 'int' || 'double' => const [
      ('EqualToComparator', 'equal'),
      ('NotEqualToComparator', 'notEqual'),
      ('LessThanComparator', 'less'),
      ('LessThanOrEqualToComparator', 'lessOrEqual'),
      ('GreaterThanComparator', 'greater'),
      ('GreaterThanOrEqualToComparator', 'greaterOrEqual'),
      ('IsBetweenComparator', 'between'),
    ],
    'string' || 'attributedString' => const [('ContainsComparator', 'contains')],
    _ => null,
  };

  /// The `EntityPropertyQuery` members of [entity]'s query, so Siri can ask
  /// for "open reminders" or "notes from yesterday". Comparators are
  /// evaluated in Swift by the runtime's `AssistantPredicate` over [all].
  String _propertyQuery(String entity, List<_Queryable> props, String all, [String access = '']) {
    final out = StringBuffer()
      ..writeln('  ${access}typealias ComparatorMappingType = AssistantPredicate<$entity>')
      ..writeln()
      ..writeln('  /// EntityPropertyQuery and EnumerableEntityQuery both provide a default.')
      ..writeln('  ${access}static var findIntentDescription: IntentDescription? { nil }')
      ..writeln()
      ..writeln('  ${access}static let properties = QueryProperties {');
    for (final q in props) {
      out.writeln('    Property(\\$entity.\$${q.member}) {');
      for (final (comparator, op) in _comparators(q.kind)!) {
        out.writeln(
          op == 'between'
              ? '      $comparator { low, high in AssistantPredicate({ \$0.${q.member} }, .between, low, high) }'
              : '      $comparator { value in AssistantPredicate({ \$0.${q.member} }, .$op, value) }',
        );
      }
      out.writeln('    }');
    }
    final sortable = [
      for (final q in props)
        if (q.sortable) q,
    ];
    out
      ..writeln('  }')
      ..writeln()
      ..writeln('  ${access}static let sortingOptions = SortingOptions {');
    for (final q in sortable) {
      out.writeln('    SortableBy(\\$entity.\$${q.member})');
    }
    out
      ..writeln('  }')
      ..writeln()
      ..writeln('  ${access}func entities(')
      ..writeln('    matching comparators: [AssistantPredicate<$entity>], mode: ComparatorMode,')
      ..writeln('    sortedBy: [EntityQuerySort<$entity>], limit: Int?')
      ..writeln('  ) async throws -> [$entity] {')
      ..writeln('    let sorts = sortedBy.compactMap { sort in')
      ..writeln('      Self.sortKey(sort.by).map { (key: \$0, ascending: sort.order == .ascending) }')
      ..writeln('    }')
      ..writeln(
        '    return AssistantPredicate.apply(comparators, all: mode == .and, to: $all, sortedBy: sorts, limit: limit)',
      )
      ..writeln('  }')
      ..writeln()
      ..writeln('  private static func sortKey(_ path: PartialKeyPath<$entity>) -> (($entity) -> AssistantKey?)? {')
      ..writeln('    switch path {');
    for (final q in sortable) {
      out.writeln('    case \\$entity.\$${q.member}: return { \$0.${q.member}${q.optional ? '?' : ''}.assistantKey }');
    }
    out
      ..writeln('    default: return nil')
      ..writeln('    }')
      ..writeln('  }');
    return out.toString();
  }

  void _snapshotAction(SnapshotActionModel a) {
    String list(Iterable<String> items) => '[${items.join(', ')}]';
    final where = a.where.isEmpty
        ? '[:]'
        : '[${a.where.entries.map((e) => '"${e.key}": ${e.value}').join(', ')}]';
    final dates = [for (final f in a.fields) if (f.type.kind == ValueKind.dateTime) '"${f.name}"'];
    _out
      ..writeln('/// `${a.name}` in Dart: answered from the published `${a.collection}` snapshot, without Flutter.')
      ..writeln('public struct ${a.swiftName}: AppIntent {')
      ..writeln('  public static let title: LocalizedStringResource = "${_escape(a.title)}"')
      ..write(_describe(a.title, a.description, a.searchKeywords, a.isDiscoverable))
      ..write(_unlockMember(_snapshotUnlock(a), access: 'public '));
    _out.writeln('''

  public init() {}

  @MainActor
  public func perform() async throws -> some IntentResult & ReturnsValue<[String]> & ProvidesDialog {
    let answer = AssistantQuery.answer(
      "${a.collection}",
      where: $where,
      sortBy: ${a.sortBy == null ? 'nil' : '"${a.sortBy}"'},
      descending: ${a.descending},
      limit: ${a.limit},
      dateFields: ${dates.isEmpty ? '[]' : list(dates)},
      titleField: ${a.titleField == null ? 'nil' : '"${a.titleField}"'},
      item: "${_escape(a.item)}",
      dialog: "${_escape(a.dialog)}",
      empty: "${_escape(a.empty)}",
      separator: "${_escape(a.separator)}")
    return .result(value: answer.items, dialog: IntentDialog(stringLiteral: answer.dialog))
  }
}
''');
  }

  // ── Spotlight ─────────────────────────────────────────────────────────

  /// Spotlight attributes the generator can fill from a schema member's
  /// `indexingKey`, with the Swift type they take.
  static const _spotlightKeys = {
    'title': 'String',
    'displayName': 'String',
    'textContent': 'String',
    'contentDescription': 'String',
    'dueDate': 'Date',
    'completionDate': 'Date',
    'contentCreationDate': 'Date',
    'contentModificationDate': 'Date',
  };

  /// `IndexedEntity` conformances, so Siri's planner finds the entities in
  /// Spotlight's semantic index, and the indexer the runtime calls on publish
  /// and on Siri's inbox changes.
  void _spotlight() {
    for (final e in app.entities) {
      _out.writeln('''
@available(iOS 18.0, macOS 15.0, *)
extension ${e.swiftName}: IndexedEntity {
  public var attributeSet: CSSearchableItemAttributeSet {
    let attributes = defaultAttributeSet
    attributes.title = title
    attributes.displayName = title
    attributes.contentDescription = subtitle
${_spotlightImage(e.image)}    return attributes
  }
}
''');
    }
    for (final s in app.schemaEntities) {
      _out
        ..writeln(_availability(_entityFloor(s.schema)))
        ..writeln('extension ${s.swiftName}: IndexedEntity {')
        ..writeln('  var attributeSet: CSSearchableItemAttributeSet {')
        ..writeln('    let attributes = defaultAttributeSet');
      for (final p in s.schema.properties) {
        final key = p.indexingKey;
        final want = _spotlightKeys[key];
        if (key == null || want == null) continue;
        final value = _spotlightValue(p, want);
        if (value != null) _out.writeln('    attributes.$key = $value');
      }
      _out
        ..write(_spotlightImage(s.image))
        ..writeln('    return attributes')
        ..writeln('  }')
        ..writeln('}')
        ..writeln();
    }

    _out
      ..writeln('/// Found by name by `AssistantSpotlight` in the runtime; apps register nothing.')
      ..writeln('@objc(AssistantActionsAppSpotlight)')
      ..writeln('public final class AssistantActionsAppSpotlight: NSObject, AssistantSpotlightIndexer {')
      ..writeln('  public func index(collection: String, removedIDs: [String], clearFirst: Bool) async throws {')
      ..writeln('    guard #available(iOS 18.0, macOS 15.0, *) else { return }')
      ..writeln('    switch collection {');
    for (final e in app.entities) {
      _out
        ..writeln('    case "${e.className}":')
        ..writeln('      try await Self.update(')
        ..writeln('        AssistantSnapshot.records("${e.className}").map(${e.swiftName}.init(record:)),')
        ..writeln('        removed: removedIDs, clearFirst: clearFirst)');
    }
    for (final s in app.schemaEntities) {
      final (iOS, macOS) = _versions(_entityFloor(s.schema));
      final update = [
        'try await Self.${s.isFile ? 'updateFiles' : 'update'}(',
        '  AssistantSnapshot.records("${s.collection}").map(${s.swiftName}.init(record:)),',
        '  removed: removedIDs, clearFirst: clearFirst)',
      ];
      _out.writeln('    case "${s.collection}":');
      // The guard above already covers iOS 18 / macOS 15.
      if (iOS <= 18 && macOS <= 15) {
        for (final line in update) {
          _out.writeln('      $line');
        }
      } else {
        _out.writeln('      if #available(iOS $iOS.0, macOS $macOS.0, *) {');
        for (final line in update) {
          _out.writeln('        $line');
        }
        _out.writeln('      }');
      }
    }
    _out.writeln('''
    default:
      break
    }
  }

  @available(iOS 18.0, macOS 15.0, *)
  private static func update<E: IndexedEntity>(_ entities: [E], removed: [String], clearFirst: Bool) async throws
  where E.ID == String {
    let index = CSSearchableIndex.default()
    if clearFirst {
      try await index.deleteAppEntities(ofType: E.self)
    } else if !removed.isEmpty {
      try await index.deleteAppEntities(identifiedBy: removed, ofType: E.self)
    }
    if !entities.isEmpty {
      try await index.indexAppEntities(entities)
    }
  }${_spotlightFiles()}
}
''');
  }

  /// A Swift expression of type [want] (`String?` / `Date?`) for member [p],
  /// or null when its type doesn't fit.
  String? _spotlightValue(SchemaMember p, String want) {
    final optional = p.type.isOptional;
    final name = p.name;
    return switch ((p.type.base.kind, want)) {
      ('string', 'String') => name,
      ('attributedString', 'String') => optional ? '$name.map { String(\$0.characters) }' : 'String($name.characters)',
      ('date', 'Date') => name,
      ('dateComponents', 'Date') =>
        optional ? '$name.flatMap { Calendar.current.date(from: \$0) }' : 'Calendar.current.date(from: $name)',
      _ => null,
    };
  }

  /// A Swift `Set<String>` literal of the lowercased words in [names] (split
  /// at camel-case humps and spaces, plus each name whole) and the app name.
  String _typeWords(List<String> names) {
    final words = <String>{};
    for (final name in [...names, app.appName]) {
      final spaced = name.replaceAllMapped(RegExp('([a-z0-9])([A-Z])'), (m) => '${m[1]} ${m[2]}');
      for (final w in spaced.toLowerCase().split(RegExp(r'[^a-z0-9]+'))) {
        if (w.isNotEmpty) words.add(w);
      }
      final whole = name.toLowerCase().replaceAll(RegExp(r'[^a-z0-9]'), '');
      if (whole.isNotEmpty) words.add(whole);
    }
    return '[${(words.toList()..sort()).map((w) => '"$w"').join(', ')}]';
  }

  // ── App Schemas ───────────────────────────────────────────────────────

  void _schemas() {
    // Every entity, enum and union schema the adopted entities and the
    // turned-on intents reach, so each gets a Swift type.
    final entities = <String>{};
    final enums = <String>{};
    final unions = <String>{};
    void visitType(SchemaType t) {
      switch (t.kind) {
        case 'optional' || 'array' || 'set':
          visitType(t.of!);
        case 'entity':
          if (t.ref != null && entities.add(t.ref!)) {
            for (final p in _entitySchema(t.ref!).properties) {
              visitType(p.type);
            }
          }
        case 'enum' || 'openEnum':
          enums.add(t.ref!);
        case 'union':
          if (unions.add(t.ref!)) {
            for (final c in _unionSchema(t.ref!).cases) {
              visitType(c.type);
            }
          }
        default:
          if (_frameworks[t.kind] case final framework?) _imports.add(framework);
      }
    }

    for (final s in app.schemaEntities) {
      visitType(SchemaType('entity', ref: s.schema.id));
      for (final (intent, _) in s.intents) {
        for (final p in intent.parameters) {
          visitType(p.type);
        }
      }
    }
    for (final d in app.schemaDomains) {
      for (final intent in d.intents) {
        for (final p in intent.parameters) {
          visitType(p.type);
        }
      }
    }
    _actionSchemaTypes.forEach(visitType);

    for (final id in enums) {
      _enum(_enumSchema(id));
    }
    for (final id in unions) {
      _union(_unionSchema(id));
    }
    for (final id in entities) {
      if (_adopted[id] case final s?) {
        _adoptedEntity(s);
      } else {
        _container(_entitySchema(id));
      }
    }
    for (final s in app.schemaEntities) {
      for (final (intent, kind) in s.intents) {
        _schemaIntent(s, intent, kind);
      }
    }
    for (final d in app.schemaDomains) {
      for (final intent in d.intents) {
        if (intent.id == 'system.open') {
          _openIntents(d, intent);
        } else {
          _callIntent(null, intent, d.handler, d.interactions, undoable: d.undoable, longRunning: d.longRunning);
        }
      }
    }
  }

  /// Frameworks some platforms lack (VisualIntelligence isn't in the iOS
  /// simulator SDK): intents that need them are left out there.
  static const _optionalFrameworks = {'VisualIntelligence'};

  /// The optional framework [intent]'s types need, if any.
  String? _optionalFramework(IntentSchema intent) {
    for (final p in intent.parameters) {
      if (_frameworks[p.type.element.kind] case final f? when _optionalFrameworks.contains(f)) return f;
    }
    return null;
  }

  /// Frameworks to import for schema value types.
  static const _frameworks = {
    'placeDescriptor': 'GeoToolbox',
    'linkMetadata': 'LinkPresentation',
    'sceneDescriptor': 'VisualIntelligence',
  };

  Iterable<DomainCatalog> get _allCatalogs => [...app.catalogs.values, for (final s in app.schemaEntities) s.catalog];

  EntitySchema _entitySchema(String id) {
    for (final c in _allCatalogs) {
      if (c.entities[id] case final e?) return e;
    }
    throw InvalidGenerationSourceError('$id is referenced but its domain catalog is not loaded.');
  }

  /// The enum schema [id], with the app's cases for one whose cases the app
  /// defines.
  EnumSchema _enumSchema(String id) {
    for (final c in _allCatalogs) {
      if (c.enums[id] case final e?) {
        if (e.cases.isNotEmpty) return e;
        // The app's cases; or, for one only reached through members Dart never
        // fills (the reader requires the app's enum for mapped fields and
        // parameters), a placeholder so the Swift type exists.
        final cases = app.openEnums[id]?.schemaCases;
        return EnumSchema(
            id: id,
            title: e.title,
            cases: cases == null || cases.isEmpty ? const ['unspecified'] : cases,
            availability: e.availability);
      }
    }
    throw InvalidGenerationSourceError('$id is referenced but its domain catalog is not loaded.');
  }

  UnionSchema _unionSchema(String id) {
    for (final c in _allCatalogs) {
      if (c.unions[id] case final u?) return u;
    }
    throw InvalidGenerationSourceError('$id is referenced but its domain catalog is not loaded.');
  }

  /// `@available(...)`: a platform missing from a catalog that names the
  /// other is unavailable there (`assistant.activate` is iOS-only).
  String _availability(Map<String, num> availability) {
    final a = _norm(availability);
    final iOS = a['iOS']!, macOS = a['macOS']!;
    if (macOS.isInfinite) return '@available(iOS ${_version(iOS)}, *)\n@available(macOS, unavailable)';
    if (iOS.isInfinite) return '@available(macOS ${_version(macOS)}, *)\n@available(iOS, unavailable)';
    return '@available(iOS ${_version(iOS)}, macOS ${_version(macOS)}, *)';
  }

  /// `27` → `27.0`, `26.2` → `26.2`.
  static String _version(num v) => v == v.truncate() ? '${v.toInt()}.0' : '$v';

  (num, num) _versions(Map<String, num> availability) {
    final a = _norm(availability);
    return (a['iOS']!, a['macOS']!);
  }

  /// Fills in platforms: none given means 27 (the first SDK with schemas
  /// whose catalog leaves it out); one given means the other is unavailable.
  static Map<String, num> _norm(Map<String, num> a) {
    if (a['iOS'] == null && a['macOS'] == null) return const {'iOS': 27, 'macOS': 27};
    return {'iOS': a['iOS'] ?? double.infinity, 'macOS': a['macOS'] ?? double.infinity};
  }

  /// The OS versions Swift types need beyond what Apple's catalog says: the
  /// journal schemas date from iOS 18, but `PlaceDescriptor` is iOS 26.
  static const _typeFloors = {
    'placeDescriptor': {'iOS': 26, 'macOS': 26},
    'sceneDescriptor': {'iOS': 26, 'macOS': 27},
    'linkMetadata': {'iOS': 26.4, 'macOS': 26.4},
    // `AppUnionValue`.
    'union': {'iOS': 27, 'macOS': 27},
  };

  static Map<String, num> _max(Map<String, num> a, Map<String, num> b) {
    final x = _norm(a), y = _norm(b);
    return {
      for (final platform in ['iOS', 'macOS']) platform: x[platform]! > y[platform]! ? x[platform]! : y[platform]!,
    };
  }

  /// The earliest OS that has [entity]'s Swift type and every type its
  /// members use.
  Map<String, num> _entityFloor(EntitySchema entity, [Set<String> seen = const {}]) {
    var floor = entity.availability;
    for (final p in entity.properties) {
      floor = _max(floor, _typeFloor(p.type, {...seen, entity.id}));
    }
    return floor;
  }

  Map<String, num> _typeFloor(SchemaType t, Set<String> seen) {
    const none = {'iOS': 0, 'macOS': 0};
    return switch (t.kind) {
      'optional' || 'array' || 'set' => _typeFloor(t.of!, seen),
      'entity' when t.ref != null && !seen.contains(t.ref) => _entityFloor(_entitySchema(t.ref!), seen),
      'enum' || 'openEnum' => _enumSchema(t.ref!).availability.isEmpty ? none : _enumSchema(t.ref!).availability,
      'union' when !seen.contains(t.ref) => _unionFloor(_unionSchema(t.ref!), {...seen, t.ref!}),
      _ => _typeFloors[t.kind] ?? none,
    };
  }

  Map<String, num> _unionFloor(UnionSchema u, Set<String> seen) {
    var floor = _max(_typeFloors['union']!, u.availability);
    for (final c in u.cases) {
      floor = _max(floor, _typeFloor(c.type, seen));
    }
    return floor;
  }

  String _unionName(String id) {
    final [domain, name] = id.split('.');
    return '${pascal(domain)}${pascal(name)}Union';
  }

  /// A schema union as a Swift `@UnionValue` enum, one case per type.
  void _union(UnionSchema u) {
    _out
      ..writeln('/// `${u.id}` ("${_escape(u.title)}"): one of ${u.cases.map((c) => c.name).join(', ')}.')
      ..writeln(_availability(_unionFloor(u, {u.id})))
      ..writeln('@UnionValue')
      ..writeln('enum ${_unionName(u.id)} {');
    for (final c in u.cases) {
      _out.writeln('  case ${swiftName(c.name)}(${_swiftType(c.type)})');
    }
    final name = _unionName(u.id);
    _out
      ..writeln('}')
      ..writeln()
      ..writeln('/// Crosses to Dart as `AssistantUnion`: `{case, kind, value}`.')
      ..writeln(_availability(_unionFloor(u, {u.id})))
      ..writeln('extension $name: AssistantEncodable {')
      ..writeln('  var assistantValue: Any {')
      ..writeln('    switch self {');
    for (final c in u.cases) {
      final member = SchemaMember(name: 'value', title: c.name, type: c.type);
      final element = c.type.element;
      final encoded = !_crossesToDart(element)
          ? 'NSNull()'
          : c.type.base.isList && element.kind != 'entity'
              ? 'value.map { AssistantValues.encode(\$0) }'
              : _encodeMember(member, 'value');
      _out.writeln('    case .${swiftName(c.name)}(let value): '
          'AssistantValues.encodeCase("${c.name}", kind: "${element.kind}", $encoded)');
    }
    _out
      ..writeln('    }')
      ..writeln('  }')
      ..writeln()
      ..writeln('  static func decode(_ value: Any?) -> $name? {')
      ..writeln('    guard let (name, raw) = AssistantValues.unionCase(value) else { return nil }')
      ..writeln('    switch name {');
    for (final c in u.cases) {
      // Entity cases decode only when the app adopts the entity.
      final t = c.type;
      if (t.base.kind == 'entity' && !_adopted.containsKey(t.base.ref)) continue;
      if (t.base.isList && t.base.of!.base.kind == 'entity' && !_adopted.containsKey(t.base.of!.base.ref)) continue;
      // Lists of values and types Dart can't send don't decode.
      if (!_crossesToDart(t.element) || (t.base.isList && t.element.kind != 'entity')) continue;
      final decoded = _decode(t.isOptional ? t : SchemaType('optional', of: t), 'raw', _unionOwner, resolve: 'true');
      _out.writeln('    case "${c.name}": return ($decoded).map { .${swiftName(c.name)}(\$0) }');
    }
    _out
      ..writeln('    default: return nil')
      ..writeln('    }')
      ..writeln('  }')
      ..writeln('}')
      ..writeln();
  }

  /// Whether values of [element] (not optional, not a list) cross to Dart.
  bool _crossesToDart(SchemaType element) =>
      element.kind == 'entity' ? element.ref != null : dartElementType(element, app.openEnumNames) != null;

