import 'package:source_gen/source_gen.dart';

import 'catalog.dart';
import 'model.dart';

/// Writes `AssistantActions.g.swift`, compiled into the generated
/// `assistant_actions_app` plugin.
class SwiftWriter {
  SwiftWriter(this.app);

  final AppModel app;
  final _out = StringBuffer();
  var _usesPlaces = false;

  /// Schema id → the app class adopting it.
  late final Map<String, SchemaEntityModel> _adopted = {for (final s in app.schemaEntities) s.schema.id: s};

  /// Container schema id → its fixed instance, from every annotation.
  final _fixed = <String, FixedInstance>{};

  String write() {
    for (final s in app.schemaEntities) {
      for (final MapEntry(:key, :value) in s.containers.entries) {
        _registerFixed(value, s, key);
      }
    }
    final body = StringBuffer();
    for (final e in app.entities) {
      _entity(e);
    }
    for (final a in app.actions) {
      _action(a);
    }
    for (final a in app.snapshotActions) {
      _snapshotAction(a);
    }
    if (app.schemaEntities.isNotEmpty) _schemas();
    body.write(_out);

    return [
      '// GENERATED by assistant_actions_generator. Do not edit.',
      '// Source: lib/assistant_actions.dart',
      '',
      'import AppIntents',
      'import Foundation',
      if (_usesPlaces) 'import GeoToolbox',
      'import assistant_actions',
      '',
      '#if os(iOS)',
      '  import UIKit',
      '#endif',
      '',
      body.toString(),
    ].join('\n');
  }

  void _registerFixed(FixedInstance fixed, SchemaEntityModel owner, String member) {
    final existing = _fixed[fixed.schema];
    if (existing != null && !existing.sameAs(fixed)) {
      throw InvalidGenerationSourceError(
          '${owner.className}.$member gives ${fixed.schema} a different fixed instance than another '
          'annotation. Use the same one everywhere.');
    }
    _fixed[fixed.schema] = fixed;
    for (final MapEntry(:key, :value) in fixed.nested.entries) {
      _registerFixed(value, owner, '$member.$key');
    }
  }

  // ── Plain entities and actions ────────────────────────────────────────

  void _entity(EntityModel e) {
    final name = e.swiftName;
    _out.writeln('''
/// `${e.className}`, published from Dart with `AssistantActions.publish`.
public struct $name: AppEntity {
  public static let typeDisplayRepresentation: TypeDisplayRepresentation = "${_escape(e.title)}"
  public static let defaultQuery = ${name}Query()

  public let id: String
  public let title: String
  public let subtitle: String?

  public var displayRepresentation: DisplayRepresentation {
    if let subtitle { return DisplayRepresentation(title: "\\(title)", subtitle: "\\(subtitle)") }
    return DisplayRepresentation(title: "\\(title)")
  }

  init(record: AssistantRecord) {
    id = record.id
    title = record.title
    subtitle = record.subtitle
  }
}

public struct ${name}Query: EntityStringQuery {
  public init() {}

  public func entities(for identifiers: [String]) async throws -> [$name] {
    let wanted = Set(identifiers)
    return AssistantSnapshot.records("${e.className}").filter { wanted.contains(\$0.id) }.map($name.init(record:))
  }

  public func entities(matching string: String) async throws -> [$name] {
    AssistantSnapshot.records("${e.className}")
      .filter { \$0.title.localizedCaseInsensitiveContains(string) }
      .map($name.init(record:))
  }

  public func suggestedEntities() async throws -> [$name] {
    AssistantSnapshot.records("${e.className}").prefix(20).map($name.init(record:))
  }
}
''');
  }

  void _action(ActionModel a) {
    final foreground = a.runs == RunsModel.withFlutter;
    _out
      ..writeln('/// `${a.functionName}` in Dart (${foreground ? 'runs with Flutter' : 'deferred'}).')
      ..writeln('public struct ${a.swiftName}: AppIntent${foreground ? ', ForegroundContinuableIntent' : ''} {')
      ..writeln('  public static let title: LocalizedStringResource = "${_escape(a.title)}"');
    if (a.description != null) {
      _out.writeln('  public static let description = IntentDescription("${_escape(a.description!)}")');
    }
    _out.writeln();
    for (final p in a.params) {
      final prompt = p.prompt == null ? '' : ', requestValueDialog: "${_escape(p.prompt!)}"';
      _out.writeln('  @Parameter(title: "${_escape(p.title)}"$prompt)\n  public var ${p.name}: ${p.swiftType}\n');
    }
    _out
      ..writeln('  public init() {}')
      ..writeln()
      ..writeln('  @MainActor')
      ..writeln('  public func perform() async throws -> some IntentResult & ProvidesDialog {')
      ..writeln(a.params.isEmpty ? '    let args: [String: Any] = [:]' : '    let args: [String: Any] = [');
    for (final p in a.params) {
      final value = p.entity != null
          ? (p.entityNullable ? 'AssistantValues.encode(${p.name}?.id)' : '${p.name}.id')
          : 'AssistantValues.encode(${p.name})';
      _out.writeln('      "${p.name}": $value,');
    }
    if (a.params.isNotEmpty) _out.writeln('    ]');
    final dialog = a.dialog == null ? '"Done."' : _interpolate(a.dialog!, a);
    if (foreground) {
      _out.writeln('''
    #if os(iOS)
      // iOS doesn't start the Flutter engine without a scene, so answer from the foreground.
      if UIApplication.shared.applicationState != .active {
        try await requestToContinueInForeground()
      }
    #endif
    let reply = try await AssistantBridge.shared.perform("${a.id}", args: args)
    return .result(dialog: IntentDialog(stringLiteral: reply ?? $dialog))''');
    } else {
      _out.writeln('''
    AssistantInbox.call("${a.id}", args: args)
    AssistantBridge.shared.inboxChanged()
    return .result(dialog: IntentDialog(stringLiteral: $dialog))''');
    }
    _out
      ..writeln('  }')
      ..writeln('}')
      ..writeln();
  }

  void _snapshotAction(SnapshotActionModel a) {
    String list(Iterable<String> items) => '[${items.join(', ')}]';
    final where = a.where.isEmpty
        ? '[:]'
        : '[${a.where.entries.map((e) => '"${e.key}": ${e.value}').join(', ')}]';
    final dates = [for (final f in a.fields) if (f.type.kind == ValueKind.dateTime) '"${f.name}"'];
    _out
      ..writeln('/// `${a.name}` in Dart: answered from the published `${a.collection}` snapshot, without Flutter.')
      ..writeln('public struct ${a.swiftName}: AppIntent {')
      ..writeln('  public static let title: LocalizedStringResource = "${_escape(a.title)}"');
    if (a.description != null) {
      _out.writeln('  public static let description = IntentDescription("${_escape(a.description!)}")');
    }
    _out.writeln('''

  public init() {}

  @MainActor
  public func perform() async throws -> some IntentResult & ReturnsValue<[String]> & ProvidesDialog {
    let answer = AssistantQuery.answer(
      "${a.collection}",
      where: $where,
      sortBy: ${a.sortBy == null ? 'nil' : '"${a.sortBy}"'},
      descending: ${a.descending},
      limit: ${a.limit},
      dateFields: ${dates.isEmpty ? '[]' : list(dates)},
      titleField: ${a.titleField == null ? 'nil' : '"${a.titleField}"'},
      item: "${_escape(a.item)}",
      dialog: "${_escape(a.dialog)}",
      empty: "${_escape(a.empty)}",
      separator: "${_escape(a.separator)}")
    return .result(value: answer.items, dialog: IntentDialog(stringLiteral: answer.dialog))
  }
}
''');
  }

  /// A Swift string literal for [template], with `{param}` interpolated.
  String _interpolate(String template, ActionModel a) {
    final escaped = _escape(template);
    return '"${escaped.replaceAllMapped(RegExp(r'\{(\w+)\}'), (m) {
      final p = a.params.firstWhere((p) => p.name == m.group(1));
      if (p.entity != null) return p.entityNullable ? '\\(${p.name}?.title ?? "")' : '\\(${p.name}.title)';
      return p.nullable ? '\\(${p.name}.map { "\\(\$0)" } ?? "")' : '\\(${p.name})';
    })}"';
  }

  // ── App Schemas ───────────────────────────────────────────────────────

  void _schemas() {
    // Every entity and enum schema the adopted entities and their intents
    // reach, so each gets a Swift type.
    final entities = <String>{};
    final enums = <String>{};
    void visitType(SchemaType t) {
      switch (t.kind) {
        case 'optional' || 'array' || 'set':
          visitType(t.of!);
        case 'entity':
          if (entities.add(t.ref!)) {
            for (final p in _entitySchema(t.ref!).properties) {
              visitType(p.type);
            }
          }
        case 'enum':
          enums.add(t.ref!);
        case 'placeDescriptor':
          _usesPlaces = true;
      }
    }

    for (final s in app.schemaEntities) {
      visitType(SchemaType('entity', ref: s.schema.id));
      for (final (intent, _) in s.intents) {
        for (final p in intent.parameters) {
          visitType(p.type);
        }
      }
    }

    for (final id in enums) {
      _enum(_enumSchema(id));
    }
    for (final id in entities) {
      if (_adopted[id] case final s?) {
        _adoptedEntity(s);
      } else {
        _container(_entitySchema(id));
      }
    }
    for (final s in app.schemaEntities) {
      for (final (intent, kind) in s.intents) {
        _schemaIntent(s, intent, kind);
      }
    }
  }

  EntitySchema _entitySchema(String id) {
    for (final s in app.schemaEntities) {
      if (s.catalog.entities[id] case final e?) return e;
    }
    throw InvalidGenerationSourceError('$id is referenced but its domain catalog is not loaded.');
  }

  EnumSchema _enumSchema(String id) {
    for (final s in app.schemaEntities) {
      if (s.catalog.enums[id] case final e?) return e;
    }
    throw InvalidGenerationSourceError('$id is referenced but its domain catalog is not loaded.');
  }

  String _availability(Map<String, num> availability) {
    String v(String platform) => '${(availability[platform] ?? 27).toInt()}.0';
    return '@available(iOS ${v('iOS')}, macOS ${v('macOS')}, *)';
  }

  String _containerName(String id) {
    final [domain, name] = id.split('.');
    return '${pascal(domain)}${pascal(name)}Entity';
  }

  String _enumName(String id) {
    final [domain, name] = id.split('.');
    return '${pascal(domain)}${pascal(name)}Enum';
  }

  String _swiftType(SchemaType t) => switch (t.kind) {
        'optional' => '${_swiftType(t.of!)}?',
        'array' => '[${_swiftType(t.of!)}]',
        'set' => 'Set<${_swiftType(t.of!)}>',
        'entity' => _adopted[t.ref]?.swiftName ?? _containerName(t.ref!),
        'enum' => _enumName(t.ref!),
        'string' => 'String',
        'attributedString' => 'AttributedString',
        'bool' => 'Bool',
        'int' => 'Int',
        'double' => 'Double',
        'date' => 'Date',
        'dateComponents' => 'DateComponents',
        'url' => 'URL',
        'file' => 'IntentFile',
        'recurrenceRule' => 'Calendar.RecurrenceRule',
        'placeDescriptor' => 'PlaceDescriptor',
        _ => throw InvalidGenerationSourceError(
            'Schema type "${t.kind}" is not supported by this version of assistant_actions yet.'),
      };

  /// Swift expression decoding [value] (an `Any?`) for a member of type [t].
  String _decode(SchemaType t, String value, EntitySchema owner) {
    final decoder = switch (t.base.kind) {
      'string' => 'AssistantValues.string($value)',
      'attributedString' => 'AssistantValues.attributed($value)',
      'bool' => 'AssistantValues.bool($value)',
      'int' => 'AssistantValues.int($value)',
      'double' => 'AssistantValues.double($value)',
      'date' => 'AssistantValues.date($value)',
      'dateComponents' => 'AssistantValues.dateComponents($value)',
      'url' => 'AssistantValues.url($value)',
      _ => throw StateError('Cannot decode ${t.kind}'),
    };
    return t.isOptional ? decoder : '$decoder ?? ${_default(t, owner, null)}';
  }

  /// The value an unmapped member of type [t] gets.
  String _default(SchemaType t, EntitySchema owner, FixedInstance? fixed) {
    if (t.kind == 'entity' && fixed != null) return '${_swiftType(t)}.fixed';
    if (t.isOptional) {
      if (t.base.kind == 'entity' && t.base.ref != owner.id && fixed != null) {
        return '${_swiftType(t.base)}.fixed';
      }
      return 'nil';
    }
    return switch (t.kind) {
      'array' || 'set' => '[]',
      'bool' => 'false',
      'string' => '""',
      'attributedString' => 'AttributedString("")',
      'enum' => '.${_enumSchema(t.ref!).cases.first}',
      _ => throw InvalidGenerationSourceError('${owner.id}: no default for a required ${t.kind}.'),
    };
  }

  /// The Swift expression for the title Siri shows, given the members.
  String _titleExpr(EntitySchema schema, String prefix) {
    final p = schema.titleProperty;
    if (p == null) return '"${_escape(schema.title)}"';
    final member = '$prefix${p.name}';
    final text = p.type.base.kind == 'attributedString' ? 'String($member.characters)' : member;
    if (!p.type.isOptional) return text;
    return p.type.base.kind == 'attributedString'
        ? '($member.map { String(\$0.characters) } ?? "")'
        : '($member ?? "")';
  }

  void _enum(EnumSchema e) {
    final name = _enumName(e.id);
    _out
      ..writeln(_availability({}))
      ..writeln('@AppEnum(schema: .${e.id})')
      ..writeln('enum $name: String {');
    for (final c in e.cases) {
      _out.writeln('  case $c');
    }
    _out
      ..writeln()
      ..writeln('  static let caseDisplayRepresentations: [$name: DisplayRepresentation] = [');
    for (final c in e.cases) {
      _out.writeln('    .$c: "${pascal(c)}",');
    }
    _out
      ..writeln('  ]')
      ..writeln('}')
      ..writeln();
  }

  void _container(EntitySchema schema) {
    final name = _containerName(schema.id);
    final fixed = _fixed[schema.id];
    _out
      ..writeln('/// `${schema.id}`, required by the adopted schemas.'
          '${fixed == null ? ' No instances.' : ' One fixed instance.'}')
      ..writeln(_availability(schema.availability))
      ..writeln('@AppEntity(schema: .${schema.id})')
      ..writeln('struct $name {')
      ..writeln('  static let defaultQuery = ${name}Query()');
    final initParams = [
      for (final p in schema.properties)
        if (p.type.base.kind == 'string' || (p.type.base.kind == 'entity' && p.type.base.ref != schema.id)) p,
    ];
    if (fixed != null) {
      final args = [
        'id: "${_escape(fixed.id)}"',
        for (final p in initParams)
          if (p.type.base.kind == 'string')
            '${p.name}: ${fixed.strings[p.name] == null ? (p.type.isOptional ? 'nil' : '""') : '"${_escape(fixed.strings[p.name]!)}"'}'
          else
            '${p.name}: ${fixed.nested[p.name] == null ? 'nil' : '${_swiftType(p.type.base)}.fixed'}',
      ];
      _out.writeln('  static let fixed = $name(${args.join(', ')})');
    }
    _out
      ..writeln()
      ..writeln('  let id: String');
    for (final p in schema.properties) {
      _out.writeln('  var ${p.name}: ${_swiftType(p.type)}');
    }
    _out
      ..writeln()
      ..writeln('  var displayRepresentation: DisplayRepresentation {'
          ' DisplayRepresentation(title: "\\(${_titleExpr(schema, '')})") }');
    if (fixed != null) {
      final params = [
        'id: String',
        for (final p in initParams)
          '${p.name}: ${p.type.base.kind == 'string' ? 'String${p.type.isOptional ? '?' : ''}' : '${_swiftType(p.type.base)}?'}',
      ];
      _out
        ..writeln()
        ..writeln('  init(${params.join(', ')}) {')
        ..writeln('    self.id = id');
      for (final p in schema.properties) {
        final isParam = initParams.contains(p);
        final value = !isParam
            ? _default(p.type, schema, null)
            : p.type.base.kind == 'entity' && !p.type.isOptional
                ? '${p.name}!'
                : p.name;
        _out.writeln('    self.${p.name} = $value');
      }
      _out.writeln('  }');
    }
    final instances = fixed == null ? '[]' : '[.fixed]';
    _out.writeln('''
}

${_availability(schema.availability)}
struct ${name}Query: EntityStringQuery {
  func entities(for identifiers: [String]) async throws -> [$name] {
    $instances.filter { identifiers.contains(\$0.id) }
  }

  func entities(matching string: String) async throws -> [$name] { $instances }

  func suggestedEntities() async throws -> [$name] { $instances }
}
''');
  }

  void _adoptedEntity(SchemaEntityModel s) {
    final schema = s.schema;
    final name = s.swiftName;
    _out
      ..writeln('/// `${s.className}` in Dart, as `${schema.id}`.')
      ..writeln(_availability(schema.availability))
      ..writeln('@AppEntity(schema: .${schema.id})')
      ..writeln('struct $name {')
      ..writeln('  static let defaultQuery = ${name}Query()')
      ..writeln()
      ..writeln('  let id: String');
    for (final p in schema.properties) {
      _out.writeln('  var ${p.name}: ${_swiftType(p.type)}');
    }
    _out
      ..writeln()
      ..writeln('  var displayRepresentation: DisplayRepresentation {'
          ' DisplayRepresentation(title: "\\(${_titleExpr(schema, '')})") }')
      ..writeln()
      ..writeln('  init(record: AssistantRecord) {')
      ..writeln('    id = record.id');
    for (final p in schema.properties) {
      final field = s.mapping[p.name];
      final value = field != null
          ? _decode(p.type, 'record.fields["${field.name}"]', schema)
          : _default(p.type, schema, s.containers[p.name]);
      _out.writeln('    ${p.name} = $value');
    }
    final collection = s.collection;
    _out.writeln('''
  }
}

${_availability(schema.availability)}
struct ${name}Query: EntityStringQuery {
  private func all() -> [$name] { AssistantSnapshot.records("$collection").map($name.init(record:)) }

  func entities(for identifiers: [String]) async throws -> [$name] {
    let wanted = Set(identifiers)
    return all().filter { wanted.contains(\$0.id) }
  }

  func entities(matching string: String) async throws -> [$name] {
    all().filter { ${_titleExpr(schema, r'$0.')}.localizedCaseInsensitiveContains(string) }
  }

  func suggestedEntities() async throws -> [$name] { Array(all().prefix(20)) }
}
''');
  }

  void _schemaIntent(SchemaEntityModel s, IntentSchema intent, IntentKind kind) {
    final entity = s.swiftName;
    final returnsEntity = intent.result?.base.kind == 'entity' && intent.result!.base.ref == s.schema.id;
    _out
      ..writeln('/// `${intent.id}` → ${kind.name}s `${s.className}` items through the inbox.')
      ..writeln(_availability(intent.availability))
      ..writeln('@AppIntent(schema: .${intent.id})')
      ..writeln('struct ${s.className}${pascal(intent.name)}Intent {');
    for (final p in intent.parameters) {
      _out.writeln('  var ${p.name}: ${_swiftType(p.type)}');
    }
    _out
      ..writeln()
      ..writeln('  @MainActor')
      ..writeln('  func perform() async throws -> some ${returnsEntity ? 'ReturnsValue<$entity>' : 'IntentResult'} {');

    // Parameters that set a mapped Dart field, grouped by field.
    final byField = <String, List<SchemaMember>>{};
    for (final p in intent.parameters) {
      if (p.name == 'target' || p.name == 'entities') continue;
      if (s.mapping[p.name] case final field?) (byField[field.name] ??= []).add(p);
    }

    switch (kind) {
      case IntentKind.create:
        _out.writeln('    var fields: [String: Any] = [:]');
        for (final MapEntry(key: field, value: params) in byField.entries) {
          _out.writeln('    fields["$field"] = ${_encodeParams(params, s)}');
        }
        _out.writeln('''
    let id = AssistantInbox.create("${s.collection}", fields: fields)
    AssistantBridge.shared.inboxChanged()
    return .result(value: $entity(record: AssistantRecord(id: id, title: "", fields: fields)))''');
      case IntentKind.update || IntentKind.append:
        _out
          ..writeln('    var fields: [String: Any] = [:]')
          ..writeln('    var cleared: [String] = []');
        for (final MapEntry(key: field, value: params) in byField.entries) {
          final clearable = kind == IntentKind.update &&
              params.length == 1 &&
              params.single.type.isOptional &&
              s.mapping[params.single.name]!.type.nullable;
          if (clearable) {
            // Three states: not given (unchanged), given as nil (cleared), or a value.
            final p = params.single.name;
            _out.writeln('''
    switch \$$p.valueState {
    case .unset: break
    case .set(let value?): fields["$field"] = AssistantValues.encode(value)
    case .set(nil): cleared.append("$field")
    }''');
          } else if (kind == IntentKind.append) {
            final p = params.first;
            final current = 'AssistantValues.string(AssistantValues.encode(target.${p.name}))';
            _out.writeln('    fields["$field"] = AssistantValues.append($current, '
                'AssistantValues.string(AssistantValues.encode(${p.name})) ?? "")');
          } else {
            final optional = params.every((p) => p.type.isOptional);
            final condition = params.map((p) => '${p.name} != nil').join(' || ');
            _out.writeln(optional
                ? '    if $condition { fields["$field"] = ${_encodeParams(params, s)} }'
                : '    fields["$field"] = ${_encodeParams(params, s)}');
          }
        }
        _out
          ..writeln('    AssistantInbox.update("${s.collection}", id: target.id, fields: fields, cleared: cleared)')
          ..writeln('    AssistantBridge.shared.inboxChanged()')
          ..writeln('    let updated = target');
        for (final field in byField.keys) {
          final members = [
            for (final MapEntry(key: member, value: f) in s.mapping.entries)
              if (f.name == field) member,
          ];
          _out.writeln('    if let value = fields["$field"] {');
          for (final member in members) {
            _out.writeln('      updated.$member = ${_decode(s.schema.property(member)!.type, 'value', s.schema)}');
          }
          final optionalMembers = [for (final m in members) if (s.schema.property(m)!.type.isOptional) m];
          if (optionalMembers.isNotEmpty) {
            _out.writeln('    } else if cleared.contains("$field") {');
            for (final member in optionalMembers) {
              _out.writeln('      updated.$member = nil');
            }
          }
          _out.writeln('    }');
        }
        _out.writeln('    return .result(value: updated)');
      case IntentKind.delete:
        _out.writeln('''
    for item in entities {
      AssistantInbox.delete("${s.collection}", id: item.id)
    }
    AssistantBridge.shared.inboxChanged()
    return .result()''');
    }
    _out
      ..writeln('  }')
      ..writeln('}')
      ..writeln();
  }

  /// Encodes the parameters that set one Dart field. Several string
  /// parameters (a note's name and content) are joined.
  String _encodeParams(List<SchemaMember> params, SchemaEntityModel s) {
    if (params.length == 1) return 'AssistantValues.encode(${params.single.name})';
    if (s.mapping[params.first.name]!.type.kind == ValueKind.string) {
      return 'AssistantValues.encodeJoined([${params.map((p) => 'AssistantValues.encode(${p.name})').join(', ')}])';
    }
    return 'AssistantValues.encode(${params.first.name})';
  }

  static String _escape(String s) => s.replaceAll(r'\', r'\\').replaceAll('"', r'\"').replaceAll('\n', r'\n');
}
