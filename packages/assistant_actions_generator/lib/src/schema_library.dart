import 'catalog.dart';
import 'interaction.dart' show canReply;
import 'schema_calls.dart';

/// Names used for a schema entity in the generated Dart library and by the
/// builder when it reads annotations back.
class SchemaNames {
  SchemaNames(this.entity);

  final EntitySchema entity;

  /// `@RemindersReminder(...)`.
  String get annotation => '${pascal(entity.domain)}${pascal(entity.name)}';

  /// `RemindersReminderField.dueDate`. Prefixed with the domain, like every
  /// name here, so libraries of several domains can be imported together
  /// (`reader.page` and `wordProcessor.page`).
  String get fields => '${annotation}Field';

  /// Type argument marking members of this schema.
  String get marker => '${annotation}Schema';

  /// `FixedRemindersList(id: ..., name: ...)`.
  String get fixed => 'Fixed$annotation';

  /// The names before 0.0.11 (`ReminderField`, `FixedList`), kept as aliases
  /// for the domains that had them.
  String get legacyFields => '${pascal(entity.name)}Field';
  String get legacyFixed => 'Fixed${pascal(entity.name)}';
}

/// Domains released before names were prefixed, which keep their old names
/// as aliases.
const _legacyDomains = {'reminders', 'notes'};

/// The schema library's file name: `wordProcessor` → `word_processor.dart`.
String schemaLibraryFile(String domain) =>
    '${domain.replaceAllMapped(RegExp('[A-Z]'), (m) => '_${m[0]!.toLowerCase()}')}.dart';

/// `@CameraIntents(...)`: the domain's intents no entity owns.
String domainAnnotation(String domain) => '${pascal(domain)}Intents';

/// Writes `package:assistant_actions/schemas/<domain>.dart` for [catalog].
String generateSchemaLibrary(DomainCatalog catalog) {
  final domain = catalog.domain;
  final example = catalog.entities.values.firstOrNull;
  final out = StringBuffer()
    ..writeln('// GENERATED by assistant_actions_generator/tool/export_catalog.dart from')
    ..writeln("// Apple's App Intents schema catalog (Xcode ${catalog.xcode}, hash ${catalog.hash.substring(0, 12)}).")
    ..writeln('// Do not edit.')
    ..writeln()
    ..writeln("/// Apple's `$domain` App Schemas, as typed annotations.")
    ..writeln('///');
  if (example != null) {
    out
      ..writeln('/// Annotate a class with an entity annotation, such as')
      ..writeln('/// `@${SchemaNames(example).annotation}(...)`, and its fields with')
      ..writeln('/// `@${SchemaNames(example).fields}.<member>`.');
  }
  if (catalog.domainIntents.isNotEmpty) {
    if (example != null) out.writeln('///');
    out
      ..writeln('/// Turn on intents that belong to no entity with `@${domainAnnotation(domain)}(...)` on the')
      ..writeln('/// class implementing the generated `${pascal(domain)}AssistantHandler`.');
  }
  if (catalog.skipped.isNotEmpty) {
    out
      ..writeln('///')
      ..writeln("/// Not adoptable: ${[for (final MapEntry(:key, :value) in catalog.skipped.entries) '`$key` ($value)'].join(', ')}.");
  }
  final usesValues = catalog.entities.values.any((e) => e.properties.any((p) => dartTypeFor(p.type)?.contains('Assistant') ?? false));
  out
    ..writeln('library;')
    ..writeln()
    ..writeln("import '../src/schema.dart';");
  if (usesValues) out.writeln("import '../src/values.dart';");

  for (final e in catalog.enums.values) {
    if (e.cases.isEmpty) {
      // The app defines the cases, on its own Dart enum.
      final name = dartEnumName(e.id);
      out
        ..writeln()
        ..writeln('/// `${e.id}` ("${e.title}"), whose cases the app defines: put `@$name()` on a')
        ..writeln('/// Dart enum, and each of its values becomes a case Siri can use.')
        ..writeln('class $name extends SchemaEnumCases {')
        ..writeln("  const $name() : super('${e.id}');")
        ..writeln('}');
      continue;
    }
    out
      ..writeln()
      ..writeln('/// `${e.id}` ("${e.title}").')
      ..writeln('enum ${dartEnumName(e.id)} {');
    for (final c in e.cases) {
      out.writeln('  ${dartName(c)},');
    }
    out.writeln('}');
  }

  for (final entity in catalog.entities.values) {
    final names = SchemaNames(entity);
    final containers = _containerMembers(catalog, entity);
    final intents = catalog.intentsFor(entity);
    out
      ..writeln()
      ..writeln('// ${'─' * 70}')
      ..writeln('// ${entity.id}')
      ..writeln()
      ..writeln('/// Adopts Apple\'s `${entity.id}` schema ("${entity.title}", ${_availability(entity.availability)}).')
      ..writeln('///')
      ..writeln('/// Map fields with [${names.fields}] and turn on the schema intents the app')
      ..writeln('/// supports. Each one becomes a method on the generated handler.');
    if (intents.isNotEmpty) {
      out
        ..writeln('///')
        ..writeln('/// `dialogs` and `confirm` give, by intent name, what Siri says when one')
        ..writeln('/// finishes and what it asks first${intents.any((e) => e.$2 == IntentKind.delete) ? ' (deletes ask by default; see `confirmDeletes`)' : ''}.');
      if (intents.any((e) => canReply(e.$1, e.$2))) {
        out.writeln('/// `replies` lets live intents\' handlers return an `AssistantReply`.');
      }
    }
    if (entity.isFile) {
      out
        ..writeln('///')
        ..writeln('/// A file entity (`FileEntity`): the `@EntityId()` is the file\'s absolute')
        ..writeln('/// path (or a `file://` URL), which Swift turns into a `FileEntityIdentifier`.')
        ..writeln('/// Ids that aren\'t paths become draft identifiers.');
    }
    if (entity.isSyncable) {
      out
        ..writeln('///')
        ..writeln('/// Syncable (`SyncableEntity`), like Apple\'s own: keep each `@EntityId()`')
        ..writeln('/// stable across launches and devices. Opt out with `@AssistantSyncable(false)`.');
    }
    out.writeln('class ${names.annotation} extends SchemaEntity {');
    final params = [
      for (final m in containers) m.type.isOptional ? 'this.${m.name},' : 'required this.${m.name},',
      for (final (intent, _) in intents) 'this.${intent.name} = false,',
      // Siri conversation options (`SchemaEntity`), for entities with intents.
      if (intents.isNotEmpty) ...['super.dialogs,', 'super.confirm,'],
      if (intents.any((e) => e.$2 == IntentKind.delete)) 'super.confirmDeletes,',
      if (intents.any((e) => canReply(e.$1, e.$2))) 'super.replies,',
    ];
    out
      ..writeln(params.isEmpty
          ? '  const ${names.annotation}()'
          : '  const ${names.annotation}({${params.join(' ')}})')
      ..writeln("      : super('${entity.id}');")
      ..writeln();
    for (final m in containers) {
      final target = SchemaNames(catalog.entities[m.type.base.ref]!).fixed;
      out
        ..writeln('  /// The fixed `${m.type.base.ref}` every item belongs to'
            '${m.type.isOptional ? ', if any.' : ' (required by the schema).'}')
        ..writeln('  final $target${m.type.isOptional ? '?' : ''} ${m.name};')
        ..writeln();
    }
    for (final (intent, kind) in intents) {
      _intentDoc(out, intent, kind, entity);
      out
        ..writeln('  final bool ${intent.name};')
        ..writeln();
    }
    out
      ..writeln('}')
      ..writeln()
      ..writeln('/// Marks members of `${entity.id}`.')
      ..writeln('final class ${names.marker} {')
      ..writeln('  const ${names.marker}._();')
      ..writeln('}')
      ..writeln();
    final mappable = [
      for (final p in entity.properties)
        if (dartTypeFor(p.type) != null) p,
    ];
    final unmapped = [
      for (final p in entity.properties)
        if (dartTypeFor(p.type) == null) p,
    ];
    out
      ..writeln('/// Members of `${entity.id}`, used as field annotations:')
      ..writeln('/// `@${names.fields}.${entity.titleProperty?.name ?? mappable.firstOrNull?.name ?? 'member'} …`.');
    if (unmapped.isNotEmpty) {
      out
        ..writeln('///')
        ..writeln('/// Not mapped to Dart yet: ${unmapped.map((p) => '`${p.name}` (`${p.type}`)').join(', ')}.'
            ' Generated entities give them their empty value.');
    }
    out.writeln('abstract final class ${names.fields} {');
    for (final p in mappable) {
      final dart = dartTypeFor(p.type)!;
      out.writeln('  /// ${p.title}${p.description == null ? '' : ': ${p.description}'}');
      if (!p.updatable) out.writeln('  ///\n  /// Read-only in the schema: Siri reads it but never sets it.');
      if (p.type.element.kind == 'entity') {
        out.writeln('  ///\n  /// The id${p.type.base.isList ? 's' : ''} of `${p.type.element.ref}` items, which the app must adopt too.');
      }
      out.writeln(
          "  static const ${dartName(p.name)} = SchemaMember<${names.marker}, $dart>('${entity.id}', '${p.name}');");
    }
    out.writeln('}');

    if (catalog.isFixable(entity)) {
      final fields = [
        for (final p in entity.properties)
          if (p.type.base.kind == 'string' ||
              (p.type.base.kind == 'entity' && p.type.base.ref != entity.id && p.type.base.ref != null))
            p,
      ];
      out
        ..writeln()
        ..writeln('/// A fixed `${entity.id}` instance, for schemas that require one.')
        ..writeln('class ${names.fixed} extends SchemaContainer {')
        ..writeln('  const ${names.fixed}({')
        ..writeln('    required String id,');
      for (final p in fields) {
        out.writeln(p.type.isOptional ? '    this.${p.name},' : '    required this.${p.name},');
      }
      out
        ..writeln("  }) : super('${entity.id}', id);")
        ..writeln();
      for (final p in fields) {
        final type = p.type.base.kind == 'string'
            ? 'String'
            : SchemaNames(catalog.entities[p.type.base.ref]!).fixed;
        out.writeln('  final $type${p.type.isOptional ? '?' : ''} ${p.name};');
      }
      out.writeln('}');
    }
  }

  if (_legacyDomains.contains(domain)) {
    out
      ..writeln()
      ..writeln('// ${'─' * 70}')
      ..writeln('// Names from before 0.0.11, when they had no domain prefix.');
    for (final entity in catalog.entities.values) {
      final names = SchemaNames(entity);
      out
        ..writeln()
        ..writeln('/// [${names.fields}], by its name before 0.0.11.')
        ..writeln('typedef ${names.legacyFields} = ${names.fields};');
      if (catalog.isFixable(entity)) {
        out
          ..writeln()
          ..writeln('/// [${names.fixed}], by its name before 0.0.11.')
          ..writeln('typedef ${names.legacyFixed} = ${names.fixed};');
      }
    }
  }

  final domainIntents = catalog.domainIntents;
  if (domainIntents.isNotEmpty) {
    final name = domainAnnotation(domain);
    out
      ..writeln()
      ..writeln('// ${'─' * 70}')
      ..writeln('// $domain intents')
      ..writeln()
      ..writeln("/// Turns on Apple's `$domain` intents that belong to no entity. Put it on")
      ..writeln('/// the class that implements the generated `${pascal(domain)}AssistantHandler`.')
      ..writeln('///')
      ..writeln('/// `dialogs` and `confirm` give, by intent name, what Siri says when one')
      ..writeln('/// finishes and what it asks first.');
    if (domainIntents.any((i) => i.isLive)) out.writeln("/// `replies` lets live intents' handlers return an `AssistantReply`.");
    out
      ..writeln('class $name extends SchemaIntents {')
      ..writeln('  const $name({${[
        for (final i in domainIntents) 'this.${i.name} = false,',
        'super.dialogs,',
        'super.confirm,',
        if (domainIntents.any((i) => i.isLive)) 'super.replies,',
      ].join(' ')}})')
      ..writeln("      : super('$domain');")
      ..writeln();
    for (final intent in domainIntents) {
      _intentDoc(out, intent, IntentKind.call, null);
      out
        ..writeln('  final bool ${intent.name};')
        ..writeln();
    }
    out.writeln('}');
  }
  return out.toString();
}

void _intentDoc(StringBuffer out, IntentSchema intent, IntentKind kind, EntitySchema? owner) {
  final head = '  /// Handle `${intent.id}` ("${intent.title}")';
  switch (kind) {
    case IntentKind.record:
      out
        ..writeln('$head: Siri brings the app to the')
        ..writeln('  /// foreground and calls `${recordMethod(intent)}()` on the generated handler.')
        ..writeln('  /// The app records the audio itself (iOS only lets the microphone start in')
        ..writeln('  /// the foreground).');
    case IntentKind.call:
      if (intent.id == 'system.open') {
        out
          ..writeln('$head: Siri opens one of the app\'s entities.')
          ..writeln('  /// Generates an `open<Class>(String id)` handler method per adopted entity.');
        return;
      }
      out
        ..writeln('$head: calls')
        ..writeln('  /// `${callSignature(intent, owner)}`')
        ..writeln(intent.isLive
            ? '  /// live${intent.opensApp ? ', with the app in the foreground' : ' (on iOS, from the foreground)'}.'
            : '  /// when the app next runs (queued, like `Runs.deferred`).');
      if (intent.description case final d?) out.writeln('  ///\n  /// $d');
      final dropped = droppedArgs(intent);
      if (dropped.isNotEmpty) {
        out.writeln('  ///\n  /// Not passed to Dart yet: ${dropped.map((p) => '`${p.name}` (`${p.type}`)').join(', ')}.');
      }
      if (callResult(intent) == CallResult.unsupported) {
        out.writeln('  ///\n  /// Not supported yet: it returns `${intent.result}`, which Dart can\'t produce.');
      }
    default:
      out.writeln('$head: ${kind.name}s items.');
  }
}

/// Members of [entity] that reference another entity the app can supply as a
/// fixed instance.
List<SchemaMember> _containerMembers(DomainCatalog catalog, EntitySchema entity) => [
      for (final p in entity.properties)
        if (p.type.base.kind == 'entity' && p.type.base.ref != entity.id && p.type.base.ref != null)
          if (catalog.entities[p.type.base.ref] case final target? when catalog.isFixable(target)) p,
    ];

String _availability(Map<String, num> availability) => [
      for (final MapEntry(:key, :value) in availability.entries) '$key ${value.toString().replaceAll(RegExp(r'\.0$'), '')}+',
    ].join(', ');
